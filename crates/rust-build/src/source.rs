/// The manifest graph no longer agrees with its lockfile. Distinguish this
/// from source acquisition and compiler errors; only this error permits
/// an automatic resolution retry.
#[derive(Debug)]
pub struct LockMismatch(pub String);

impl std::fmt::Display for LockMismatch {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(formatter, "lockfile mismatch: {}", self.0)
    }
}

impl std::error::Error for LockMismatch {}

#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct LockedPackage {
    pub name: String,
    pub version: Version,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub source: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub checksum: Option<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub dependencies: Vec<String>,
}

#[derive(Debug, Default, Deserialize, Serialize)]
pub struct Lockfile {
    pub version: Option<u32>,
    #[serde(default, rename = "package")]
    pub packages: Vec<LockedPackage>,
}

impl Lockfile {
    pub fn load(path: &Path) -> Result<Self> {
        if !path.exists() {
            return Ok(Self::default());
        }
        let lock: Self = toml::from_str(&fs::read_to_string(path)?)?;
        ensure!(
            matches!(lock.version, Some(3 | 4)),
            "unsupported lockfile version {:?}",
            lock.version
        );
        Ok(lock)
    }

    pub fn write(&self, path: &Path) -> Result<()> {
        use std::io::Write;
        let mut file =
            tempfile::NamedTempFile::new_in(path.parent().context("lockfile parent missing")?)?;
        writeln!(file, "# Generated by sccache native Rust resolver.")?;
        file.write_all(toml::to_string(self)?.as_bytes())?;
        file.as_file().sync_all()?;
        file.persist(path)?;
        Ok(())
    }
}

// A per-key slot serializes acquisition of the same immutable source while
// unrelated packages can download, verify and unpack concurrently.
struct Memo<K, V> {
    slots: Mutex<BTreeMap<K, Arc<Mutex<Option<V>>>>>,
}

impl<K, V> Default for Memo<K, V> {
    fn default() -> Self {
        Self {
            slots: Mutex::new(BTreeMap::new()),
        }
    }
}

impl<K: Ord, V: Clone> Memo<K, V> {
    fn get(&self, key: K, acquire: impl FnOnce() -> Result<V>) -> Result<V> {
        let slot = {
            let mut slots = self
                .slots
                .lock()
                .map_err(|_| anyhow::anyhow!("source memo poisoned"))?;
            Arc::clone(slots.entry(key).or_default())
        };
        let mut value = slot
            .lock()
            .map_err(|_| anyhow::anyhow!("source acquisition slot poisoned"))?;
        if let Some(value) = value.as_ref() {
            return Ok(value.clone());
        }
        let acquired = acquire()?;
        *value = Some(acquired.clone());
        Ok(acquired)
    }
}

pub struct Sources<'a> {
    pub workspace: &'a Workspace,
    lock: Lockfile,
    lock_index: BTreeMap<String, Vec<usize>>,
    pub import_root: Option<PathBuf>,
    pub scratch: PathBuf,
    /// Stream a verified registry archive to the provided staging file.
    pub download: Option<&'a (dyn Fn(&str, &mut fs::File) -> Result<()> + Sync)>,
    pub archive:
        Option<&'a (dyn Fn(&LockedPackage, &Registry, &mut fs::File) -> Result<bool> + Sync)>,
    pub registries: Registries,
    materialized: Memo<String, PathBuf>,
    manifests: Memo<PathBuf, Manifest>,
    git_checkouts: Memo<String, PathBuf>,
    git_packages: Memo<String, Vec<Manifest>>,
}

pub(crate) fn identity(package: &LockedPackage) -> String {
    format!(
        "{} {} {}",
        package.name,
        package.version,
        package.source.as_deref().unwrap_or("path")
    )
}

pub(crate) fn locked_edge(edge: &str, package: &LockedPackage) -> bool {
    let mut fields = edge.splitn(3, ' ');
    if fields.next() != Some(package.name.as_str()) {
        return false;
    }
    if let Some(version) = fields.next() {
        if version != package.version.to_string() {
            return false;
        }
    }
    if let Some(source) = fields.next() {
        return source.strip_prefix('(').and_then(|s| s.strip_suffix(')'))
            == package.source.as_deref();
    }
    true
}

impl<'a> Sources<'a> {
    pub fn new(
        workspace: &'a Workspace,
        lock: Lockfile,
        import_root: Option<PathBuf>,
        scratch: PathBuf,
    ) -> Self {
        Self {
            workspace,
            lock_index: Self::index(&lock),
            lock,
            import_root,
            scratch,
            download: None,
            archive: None,
            registries: Registries::default(),
            materialized: Memo::default(),
            manifests: Memo::default(),
            git_checkouts: Memo::default(),
            git_packages: Memo::default(),
        }
    }

    fn index(lock: &Lockfile) -> BTreeMap<String, Vec<usize>> {
        let mut index = BTreeMap::<String, Vec<usize>>::new();
        for (i, package) in lock.packages.iter().enumerate() {
            index.entry(package.name.clone()).or_default().push(i);
        }
        index
    }

    pub fn lock(&self) -> &Lockfile {
        &self.lock
    }

    pub fn replace_lock(&mut self, lock: Lockfile) {
        self.lock_index = Self::index(&lock);
        self.lock = lock;
    }

    fn packages_named(&self, name: &str) -> impl Iterator<Item = &LockedPackage> {
        self.lock_index
            .get(name)
            .into_iter()
            .flatten()
            .map(|&i| &self.lock.packages[i])
    }

    pub(crate) fn locked_parent(
        &self,
        manifest: &Manifest,
        source: Option<&str>,
    ) -> Result<Option<&LockedPackage>> {
        let mut matches = self
            .packages_named(&manifest.package.name)
            .filter(|p| p.version == manifest.package.version && p.source.as_deref() == source);
        let result = matches.next();
        ensure!(
            matches.next().is_none(),
            "ambiguous lock identity for {}",
            manifest.package.name
        );
        Ok(result)
    }

    pub(crate) fn manifest(&self, root: &Path) -> Result<Manifest> {
        let root = root.canonicalize()?;
        self.manifests.get(root.clone(), || {
            if self.workspace.members.contains(&root) {
                self.workspace.package(&root)
            } else {
                load_discovered(&root)
            }
        })
    }

    /// The lockfile provides the selected exact versions, including duplicate
    /// semver-compatible versions. Never substitute a newer cached package.
    pub fn dependency(
        &self,
        parent: &Manifest,
        parent_source: Option<&str>,
        dep: &Dependency,
    ) -> Result<(Manifest, Option<String>)> {
        if let Some(path) = &dep.path {
            let root = path
                .canonicalize()
                .with_context(|| format!("resolve path dependency {}", dep.alias))?;
            let manifest = self.manifest(&root)?;
            validate_dependency(&manifest, dep)?;
            let mut child_source = parent_source.map(str::to_owned);
            if !self.lock.packages.is_empty() {
                let locked = self
                    .locked_parent(parent, parent_source)?
                    .ok_or_else(|| LockMismatch(format!("{} is absent", parent.package.name)))?;
                let child = self
                    .locked_parent(&manifest, parent_source)?
                    .or(self.locked_parent(&manifest, None)?)
                    .ok_or_else(|| {
                        LockMismatch(format!("path dependency {} is absent", dep.alias))
                    })?;
                if !locked
                    .dependencies
                    .iter()
                    .any(|edge| locked_edge(edge, child))
                {
                    return Err(LockMismatch(format!("path edge {} is absent", dep.alias)).into());
                }
                child_source = child.source.clone();
            }
            return Ok((manifest, child_source));
        }
        let parent_lock = self.locked_parent(parent, parent_source)?.ok_or_else(|| {
            LockMismatch(format!(
                "{} has no locked edge for {}",
                parent.package.name, dep.alias
            ))
        })?;
        let mut candidates = Vec::new();
        for package in self.packages_named(&dep.name) {
            if dep.requirement.matches(&package.version)
                && parent_lock
                    .dependencies
                    .iter()
                    .any(|edge| locked_edge(edge, package))
                && self.matches_source(dep, package)?
            {
                candidates.push(package.clone());
            }
        }
        if candidates.len() != 1 {
            return Err(LockMismatch(format!(
                "edge {} -> {} has {} candidates",
                parent.package.name,
                dep.alias,
                candidates.len()
            ))
            .into());
        }
        let locked = &candidates[0];
        let root = match locked.source.as_deref() {
            Some(source) if source.starts_with("registry+") || source.starts_with("sparse+") => {
                self.registry(locked)?
            }
            Some(source) if source.starts_with("git+") => self.git(locked)?,
            None => self.patched_path(dep, locked)?,
            Some(source) => bail!("unsupported locked source {source}"),
        };
        let manifest = self.manifest(&root)?;
        validate_dependency(&manifest, dep)?;
        ensure!(
            manifest.package.version == locked.version,
            "locked package version mismatch"
        );
        Ok((manifest, locked.source.clone()))
    }

    pub(crate) fn patches(&self, dep: &Dependency) -> Result<Vec<Dependency>> {
        let Some(patches) = self
            .workspace
            .document
            .get("patch")
            .and_then(toml::Value::as_table)
        else {
            return Ok(Vec::new());
        };
        let mut result = Vec::new();
        let registry = if dep.git.is_none() {
            Some(self.registries.get(dep.registry.as_deref())?)
        } else {
            None
        };
        for (source, values) in patches {
            let matches = if let Some(git) = dep.git.as_deref() {
                source.trim_end_matches('/') == git.trim_end_matches('/')
            } else if let Some(registry) = registry {
                self.registries
                    .get(Some(source))
                    .is_ok_and(|other| other.source == registry.source)
            } else {
                false
            };
            if !matches {
                continue;
            }
            let values = values.as_table().context("patch source must be a table")?;
            for (alias, value) in values {
                let patch = crate::manifest::dependency(
                    alias,
                    value,
                    dep.kind,
                    dep.platform.as_deref(),
                    &self.workspace.root,
                    Some(self.workspace),
                )?;
                if patch.name == dep.name {
                    result.push(patch);
                }
            }
        }
        Ok(result)
    }

    fn matches_source(&self, dep: &Dependency, package: &LockedPackage) -> Result<bool> {
        let original = if dep.git.is_some() {
            package
                .source
                .as_deref()
                .is_some_and(|source| matches_git_source(dep, source))
        } else {
            let registry = self.registries.get(dep.registry.as_deref())?;
            package
                .source
                .as_deref()
                .is_some_and(|source| self.registries.matches(registry, source))
        };
        if original {
            return Ok(true);
        }
        for patch in self.patches(dep)? {
            if !patch.requirement.matches(&package.version) {
                continue;
            }
            if patch.path.is_some() && package.source.is_none() {
                return Ok(true);
            }
            if patch.git.is_some()
                && package
                    .source
                    .as_deref()
                    .is_some_and(|source| matches_git_source(&patch, source))
            {
                return Ok(true);
            }
            if patch.registry.is_some() {
                let registry = self.registries.get(patch.registry.as_deref())?;
                if package
                    .source
                    .as_deref()
                    .is_some_and(|source| self.registries.matches(registry, source))
                {
                    return Ok(true);
                }
            }
        }
        Ok(false)
    }

    fn patched_path(&self, dep: &Dependency, package: &LockedPackage) -> Result<PathBuf> {
        let mut found = BTreeSet::new();
        for patch in self.patches(dep)? {
            if !patch.requirement.matches(&package.version) {
                continue;
            }
            if let Some(path) = patch.path {
                let path = path.canonicalize()?;
                let manifest = self.manifest(&path)?;
                if manifest.package.name == package.name
                    && manifest.package.version == package.version
                {
                    found.insert(path);
                }
            }
        }
        if found.len() != 1 {
            return Err(LockMismatch(format!(
                "cannot locate unique declared path patch {}",
                identity(package)
            ))
            .into());
        }
        found.pop_first().context("missing path patch")
    }

    fn registry(&self, package: &LockedPackage) -> Result<PathBuf> {
        let checksum = package
            .checksum
            .as_deref()
            .context("registry lock has no checksum")?;
        let key = format!("{} {checksum}", identity(package));
        self.materialized
            .get(key.clone(), || self.registry_uncached(package, &key))
    }

    fn registry_uncached(&self, package: &LockedPackage, key: &str) -> Result<PathBuf> {
        let source = package
            .source
            .as_deref()
            .context("missing registry source")?;
        let registry = self.registries.get(Some(source))?.clone();
        let checksum = package
            .checksum
            .as_ref()
            .context("registry lock has no checksum")?;
        let name = &package.name;
        ensure!(
            name.bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_'),
            "invalid registry package name"
        );
        let stem = format!("{}-{}", name, package.version);
        let filename = format!("{stem}.crate");
        let root = self
            .scratch
            .join("registry")
            .join(blake3::hash(key.as_bytes()).to_hex().as_str());
        if root.exists() {
            fs::remove_dir_all(&root)?;
        }
        fs::create_dir_all(&root)?;
        // A verified, private descriptor is the only archive passed to
        // the decoder. Never verify one mutable path and subsequently
        // decode different bytes from it.
        let mut file = tempfile::tempfile_in(&root)?;
        let mut found = false;
        if let Some(import) = &self.import_root {
            let cache = import.join("registry/cache");
            if cache.is_dir() {
                for entry in fs::read_dir(cache)? {
                    let path = entry?.path().join(&filename);
                    if path.is_file() {
                        file.set_len(0)?;
                        file.seek(SeekFrom::Start(0))?;
                        std::io::copy(&mut fs::File::open(path)?, &mut file)?;
                        if verify(&mut file, checksum)? {
                            found = true;
                            break;
                        }
                    }
                }
            }
        }
        if !found && let Some(archive) = self.archive {
            file.set_len(0)?;
            file.seek(SeekFrom::Start(0))?;
            found = archive(package, &registry, &mut file)?;
            if found {
                ensure!(
                    verify(&mut file, checksum)?,
                    "scheduler archive checksum mismatch for {stem}"
                );
            }
            ensure!(
                found,
                "registry package {stem} not present in the shared CAS"
            );
        }
        if !found {
            let download = self
                .download
                .context("locked crate archive not available offline")?;
            file.set_len(0)?;
            file.seek(SeekFrom::Start(0))?;
            download(
                &registry.archive_url(name, &package.version.to_string(), checksum)?,
                &mut file,
            )?;
            ensure!(
                verify(&mut file, checksum)?,
                "download checksum mismatch for {stem}"
            );
        }
        let mut tar = tar::Archive::new(flate2::read::GzDecoder::new(file));
        tar.set_preserve_mtime(false);
        for entry in tar.entries()? {
            let mut entry = entry?;
            let path = entry.path()?.into_owned();
            ensure!(
                path.starts_with(&stem),
                "archive entry outside package root"
            );
            ensure!(
                entry.header().entry_type().is_file() || entry.header().entry_type().is_dir(),
                "unsupported registry archive entry"
            );
            ensure!(entry.unpack_in(&root)?, "invalid registry archive path");
        }
        Ok(root.join(stem))
    }

    fn git(&self, package: &LockedPackage) -> Result<PathBuf> {
        let key = identity(package);
        self.materialized.get(key.clone(), || {
            let source = package.source.as_deref().context("missing git source")?;
            let mut found = self
                .git_manifests(source, &package.name)?
                .into_iter()
                .filter(|manifest| manifest.package.version == package.version)
                .collect::<Vec<_>>();
            ensure!(
                found.len() == 1,
                "cannot locate unique locked git package {key}"
            );
            Ok(found.remove(0).root)
        })
    }

    pub(crate) fn git_source(&self, dep: &Dependency) -> Result<String> {
        let prefix = git_source_prefix(dep)?;
        let mut pinned = self
            .lock
            .packages
            .iter()
            .filter_map(|p| p.source.as_deref())
            .filter(|source| {
                source
                    .split_once('#')
                    .is_some_and(|(source, _)| source == prefix)
            })
            .collect::<BTreeSet<_>>();
        if pinned.len() == 1 {
            return Ok(pinned.pop_first().context("missing git pin")?.to_owned());
        }
        ensure!(
            pinned.is_empty(),
            "ambiguous existing Git source pins for {}",
            dep.alias
        );
        let url = dep.git.as_deref().context("missing Git URL")?;
        let reference = match dep
            .git_reference
            .as_ref()
            .map(|(key, value)| (key.as_str(), value.as_str()))
        {
            Some(("rev", value))
                if value.len() == 40 && value.bytes().all(|b| b.is_ascii_hexdigit()) =>
            {
                return Ok(format!("{prefix}#{value}"));
            }
            Some(("branch", value)) => format!("refs/heads/{value}"),
            Some(("tag", value)) => format!("refs/tags/{value}"),
            Some(("rev", value)) => value.to_owned(),
            None => "HEAD".to_owned(),
            Some((key, _)) => bail!("invalid Git reference type {key}"),
        };
        // First resolve a reference in the imported object's repository.
        if self.download.is_none() {
            let import = self
                .import_root
                .as_ref()
                .context("offline Git reference needs an object cache")?;
            let mut commits = BTreeSet::new();
            for entry in fs::read_dir(import.join("git/db"))? {
                let root = entry?.path();
                let origin = Command::new("git")
                    .arg("--git-dir")
                    .arg(&root)
                    .args(["config", "--get", "remote.origin.url"])
                    .output()?;
                if !origin.status.success() || String::from_utf8_lossy(&origin.stdout).trim() != url
                {
                    continue;
                }
                let output = Command::new("git")
                    .arg("--git-dir")
                    .arg(&root)
                    .args(["rev-parse", "--verify", &format!("{reference}^{{commit}}")])
                    .output()?;
                if output.status.success() {
                    commits.insert(String::from_utf8(output.stdout)?.trim().to_owned());
                }
            }
            ensure!(
                commits.len() == 1,
                "cannot uniquely resolve offline Git reference {reference}"
            );
            return Ok(format!(
                "{prefix}#{}",
                commits.pop_first().context("missing commit")?
            ));
        }
        let output = Command::new("git")
            .args([
                "ls-remote",
                "--",
                url,
                &reference,
                &format!("{reference}^{{}}"),
            ])
            .output()?;
        ensure!(
            output.status.success(),
            "cannot resolve Git reference {}",
            dep.alias
        );
        let output = String::from_utf8(output.stdout)?;
        let mut candidates = output
            .lines()
            .filter_map(|line| line.split_once('\t'))
            .collect::<Vec<_>>();
        candidates.sort_by_key(|(_, name)| !name.ends_with("^{}"));
        let (commit, _) = candidates
            .first()
            .context("Git reference did not resolve")?;
        ensure!(
            commit.len() == 40 && commit.bytes().all(|b| b.is_ascii_hexdigit()),
            "invalid Git commit"
        );
        Ok(format!("{prefix}#{commit}"))
    }

    fn git_checkout(&self, source: &str) -> Result<PathBuf> {
        self.git_checkouts
            .get(source.to_owned(), || self.git_checkout_uncached(source))
    }

    fn git_checkout_uncached(&self, source: &str) -> Result<PathBuf> {
        let (url, commit) = source
            .strip_prefix("git+")
            .context("not a git source")?
            .rsplit_once('#')
            .context("git lock lacks commit")?;
        ensure!(
            commit.len() == 40 && commit.bytes().all(|b| b.is_ascii_hexdigit()),
            "invalid git commit"
        );
        let url = url.split('?').next().context("missing git URL")?;
        let root = self
            .scratch
            .join("git")
            .join(blake3::hash(source.as_bytes()).to_hex().as_str());
        if !root.join(".git/sccache-source-ready").is_file() {
            if root.exists() {
                fs::remove_dir_all(&root)?;
            }
            fs::create_dir_all(&root)?;
            let mut repository = None;
            if let Some(import) = &self.import_root {
                let db = import.join("git/db");
                if db.is_dir() {
                    for entry in fs::read_dir(db)? {
                        let path = entry?.path();
                        if Command::new("git")
                            .arg("--git-dir")
                            .arg(&path)
                            .args(["cat-file", "-e", &format!("{commit}^{{commit}}")])
                            .stdout(Stdio::null())
                            .stderr(Stdio::null())
                            .status()?
                            .success()
                        {
                            repository = Some(path);
                            break;
                        }
                    }
                }
            }
            if repository.is_none() {
                ensure!(
                    self.download.is_some(),
                    "locked git commit is not available offline"
                );
                let repo = self
                    .scratch
                    .join("git-objects")
                    .join(blake3::hash(source.as_bytes()).to_hex().as_str());
                fs::create_dir_all(&repo)?;
                ensure!(
                    Command::new("git")
                        .arg("-C")
                        .arg(&repo)
                        .args(["init", "--bare", "--quiet"])
                        .status()?
                        .success(),
                    "git init failed"
                );
                ensure!(
                    Command::new("git")
                        .arg("-C")
                        .arg(&repo)
                        .args(["fetch", "--no-tags", "--depth=1", "--", url, commit])
                        .status()?
                        .success(),
                    "git fetch failed"
                );
                repository = Some(repo);
            }
            let repo = repository.context("missing git object database")?;
            // Use an actual isolated checkout rather than git archive:
            // export-ignore and export-subst must not change source inputs,
            // and build scripts must be able to query the pinned commit.
            ensure!(
                Command::new("git")
                    .arg("-C")
                    .arg(&root)
                    .args(["init", "--quiet"])
                    .status()?
                    .success(),
                "git init failed"
            );
            ensure!(
                Command::new("git")
                    .arg("-C")
                    .arg(&root)
                    .args(["fetch", "--no-tags", "--depth=1", "--"])
                    .arg(&repo)
                    .arg(commit)
                    .status()?
                    .success(),
                "cannot import locked git objects"
            );
            ensure!(
                Command::new("git")
                    .arg("-C")
                    .arg(&root)
                    .args(["remote", "add", "origin", url])
                    .status()?
                    .success(),
                "cannot configure source origin"
            );
            ensure!(
                Command::new("git")
                    .arg("-C")
                    .arg(&root)
                    .args([
                        "-c",
                        "core.autocrlf=false",
                        "-c",
                        "core.symlinks=true",
                        "checkout",
                        "--detach",
                        "--force",
                        commit
                    ])
                    .status()?
                    .success(),
                "cannot check out locked git commit"
            );
            let listing = Command::new("git")
                .arg("-C")
                .arg(&root)
                .args(["ls-tree", "-r", "-z", commit])
                .output()?;
            ensure!(listing.status.success(), "git tree inspection failed");
            if listing
                .stdout
                .split(|b| *b == 0)
                .any(|line| line.starts_with(b"160000 "))
            {
                ensure!(
                    self.download.is_some(),
                    "locked git submodules require online acquisition"
                );
                ensure!(
                    Command::new("git")
                        .arg("-C")
                        .arg(&root)
                        .args([
                            "submodule",
                            "update",
                            "--init",
                            "--recursive",
                            "--checkout",
                            "--depth=1"
                        ])
                        .status()?
                        .success(),
                    "cannot acquire pinned git submodules"
                );
            }
            fs::write(root.join(".git/sccache-source-ready"), commit)?;
        }
        Ok(root)
    }

    pub(crate) fn git_manifests(&self, source: &str, name: &str) -> Result<Vec<Manifest>> {
        let all = self.git_packages.get(source.to_owned(), || {
            let root = self.git_checkout(source)?;
            fn find(sources: &Sources<'_>, root: &Path, found: &mut Vec<Manifest>) -> Result<()> {
                if root.join("Cargo.toml").is_file()
                    && let Ok(manifest) = sources.manifest(root)
                {
                    found.push(manifest);
                }
                for entry in fs::read_dir(root)? {
                    let entry = entry?;
                    if entry.file_type()?.is_dir()
                        && !entry.file_name().to_string_lossy().starts_with('.')
                    {
                        find(sources, &entry.path(), found)?;
                    }
                }
                Ok(())
            }
            let mut found = Vec::new();
            find(self, &root, &mut found)?;
            Ok(found)
        })?;
        Ok(all
            .into_iter()
            .filter(|manifest| manifest.package.name == name)
            .collect())
    }
}

fn git_source_prefix(dep: &Dependency) -> Result<String> {
    let url = dep.git.as_deref().context("missing git source")?;
    let mut source = format!("git+{url}");
    if let Some((key, value)) = &dep.git_reference {
        ensure!(!value.contains(['#', '&', '?']), "ambiguous git reference");
        source.push('?');
        source.push_str(key);
        source.push('=');
        source.push_str(value);
    }
    Ok(source)
}

fn matches_git_source(dep: &Dependency, source: &str) -> bool {
    git_source_prefix(dep).is_ok_and(|prefix| {
        source
            .split_once('#')
            .is_some_and(|(source, _)| source == prefix)
    })
}

pub(crate) fn load_discovered(root: &Path) -> Result<Manifest> {
    let workspace = Workspace::discover(&root.join("Cargo.toml"))?;
    workspace.package(root)
}

pub(crate) fn validate_dependency(manifest: &Manifest, dep: &Dependency) -> Result<()> {
    ensure!(
        manifest.package.name == dep.name && dep.requirement.matches(&manifest.package.version),
        "dependency {} resolved to wrong package {} {}",
        dep.alias,
        manifest.package.name,
        manifest.package.version
    );
    Ok(())
}

fn verify(file: &mut fs::File, checksum: &str) -> Result<bool> {
    file.seek(SeekFrom::Start(0))?;
    let mut sha = Sha256::new();
    let mut buffer = vec![0u8; 128 * 1024];
    loop {
        let read = match file.read(&mut buffer) {
            Err(error) if error.kind() == std::io::ErrorKind::Interrupted => continue,
            result => result?,
        };
        if read == 0 {
            break;
        }
        sha.update(&buffer[..read]);
    }
    file.seek(SeekFrom::Start(0))?;
    let actual = sha
        .finalize()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect::<String>();
    Ok(actual == checksum)
}
