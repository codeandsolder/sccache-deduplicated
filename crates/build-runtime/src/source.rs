//! Metadata and mutation detection for regular source files and snapshots.
use anyhow::{Result, ensure};
use rustix::fs::Stat;

use crate::{TreeMetadata, TreeTimestamp};

pub(crate) fn timestamp(stat: &Stat) -> Result<TreeTimestamp> {
    Ok(TreeTimestamp {
        seconds: stat.st_mtime,
        nanoseconds: u32::try_from(stat.st_mtime_nsec)?,
    })
}

pub(crate) fn metadata(stat: &Stat) -> Result<TreeMetadata> {
    Ok(TreeMetadata {
        mode: stat.st_mode & 0o7777,
        modified: timestamp(stat)?,
    })
}

pub(crate) fn unchanged(before: &Stat, after: &Stat) -> Result<()> {
    ensure!(
        before.st_dev == after.st_dev
            && before.st_ino == after.st_ino
            && before.st_mode == after.st_mode
            && before.st_nlink == after.st_nlink
            && before.st_size == after.st_size
            && before.st_mtime == after.st_mtime
            && before.st_mtime_nsec == after.st_mtime_nsec
            && before.st_ctime == after.st_ctime
            && before.st_ctime_nsec == after.st_ctime_nsec,
        "native snapshot changed during capture"
    );
    Ok(())
}
