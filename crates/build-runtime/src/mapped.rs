#[cfg(all(test, feature = "store"))]
#[test]
fn mixed_reference_tree_preserves_identity_and_reads_only_missing_content() -> Result<()> {
    use std::sync::atomic::{AtomicUsize, Ordering};
    let dir = tempfile::tempdir()?;
    let file = dir.path().join("source");
    std::fs::write(&file, b"local")?;
    let metadata = TreeMetadata {
        mode: 0o644,
        modified: TreeTimestamp {
            seconds: 1,
            nanoseconds: 0,
        },
    };
    let known = BlobRef {
        id: ContentId::of(b"retained"),
        size: 8,
    };
    let opens = Arc::new(AtomicUsize::new(0));
    let count = Arc::clone(&opens);
    let provider = ReferenceBlobProvider::new(move |blob| {
        ensure!(blob == known, "undeclared test blob");
        count.fetch_add(1, Ordering::Relaxed);
        Ok(Box::new(Cursor::new(b"retained")))
    });
    let mut referenced = MappedTree::new(metadata);
    referenced.add_file(
        TreePath::new(b"source".to_vec())?,
        file.clone(),
        MappedMetadata::Normalize(metadata.modified),
    )?;
    referenced.add_reference(
        TreePath::new(b"dependency".to_vec())?,
        known,
        metadata,
        provider,
    )?;
    let referenced = referenced.prepare()?;
    let mut ordinary = MappedTree::new(metadata);
    ordinary.add_file(
        TreePath::new(b"source".to_vec())?,
        file,
        MappedMetadata::Normalize(metadata.modified),
    )?;
    ordinary.add_bytes(
        TreePath::new(b"dependency".to_vec())?,
        b"retained".to_vec(),
        metadata,
    )?;
    let ordinary = ordinary.prepare()?;
    assert_eq!(referenced.id(), ordinary.id());
    assert!(referenced.open_local_blob(known.id).is_err());
    assert_eq!(opens.load(Ordering::Relaxed), 0);
    let store = crate::NativeStore::open(&dir.path().join("store"))?;
    let _ordinary = ordinary.import(&store)?;
    let _referenced = referenced.import(&store)?;
    assert_eq!(opens.load(Ordering::Relaxed), 0);
    let other = crate::NativeStore::open(&dir.path().join("other"))?;
    let _copied = referenced.import(&other)?;
    assert_eq!(opens.load(Ordering::Relaxed), 1);
    Ok(())
}
