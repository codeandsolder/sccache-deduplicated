/// File metadata contract for a mapped build tree. Normalization is explicit
/// and affects the actual materialized inode, not merely its cache key.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MappedMetadata {
    Preserve,
    /// Keep exact permission bits, but give the materialized input a stable timestamp.
    NormalizeTimestamp(TreeTimestamp),
    Normalize(TreeTimestamp),
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum Source {
    Directory(TreeMetadata),
    File {
        path: PathBuf,
        metadata: MappedMetadata,
    },
    Bytes {
        data: Vec<u8>,
        metadata: TreeMetadata,
    },
    Reference {
        blob: BlobRef,
        metadata: TreeMetadata,
        provider: ReferenceBlobProvider,
    },
    Symlink {
        target: Vec<u8>,
        modified: TreeTimestamp,
    },
}

/// A lazy source backed by an authoritative content lease. Cloning it
/// retains that lease. A consumer always verifies supplied bytes.
#[derive(Clone)]
pub struct ReferenceBlobProvider(
    Arc<dyn Fn(BlobRef) -> Result<Box<dyn Read + Send>> + Send + Sync>,
);

impl ReferenceBlobProvider {
    #[must_use = "the provider owns the content lease"]
    pub fn new(
        provider: impl Fn(BlobRef) -> Result<Box<dyn Read + Send>> + Send + Sync + 'static,
    ) -> Self {
        Self(Arc::new(provider))
    }

    /// Open immutable content. The receiver must verify the digest and length.
    /// # Errors
    /// Returns an error if the content lease or source is unavailable.
    pub fn open(&self, blob: BlobRef) -> Result<Box<dyn Read + Send>> {
        (self.0)(blob)
    }
}

impl std::fmt::Debug for ReferenceBlobProvider {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("ReferenceBlobProvider")
    }
}

impl PartialEq for ReferenceBlobProvider {
    fn eq(&self, other: &Self) -> bool {
        Arc::ptr_eq(&self.0, &other.0)
    }
}
impl Eq for ReferenceBlobProvider {}

/// A descriptor-based resolver for explicitly authorized immutable references.
/// Returning None selects ordinary verified file capture.
pub type ReferenceResolver<'a> =
    dyn Fn(&File, &Path) -> Result<Option<(BlobRef, ReferenceBlobProvider)>> + 'a;

/// A collection of caller-selected files, generated bytes and symlinks at
/// canonical sandbox-relative paths. Implicit parent directories get the
/// explicit directory metadata supplied at construction.
pub struct MappedTree {
    directories: TreeMetadata,
    entries: BTreeMap<TreePath, Source>,
}

impl MappedTree {
    #[must_use = "the mapping must be populated and captured"]
    pub const fn new(directories: TreeMetadata) -> Self {
        Self {
            directories,
            entries: BTreeMap::new(),
        }
    }

    fn insert(&mut self, path: TreePath, source: Source) -> Result<()> {
        match self.entries.entry(path) {
            Entry::Vacant(entry) => {
                entry.insert(source);
            }
            Entry::Occupied(entry) => {
                ensure!(entry.get() == &source, "conflicting mapped tree paths");
            }
        }
        Ok(())
    }

    /// Add a directory with the mapping's directory metadata.
    ///
    /// # Errors
    /// Returns an error for a conflicting entry.
    pub fn add_directory(&mut self, path: TreePath) -> Result<()> {
        self.insert(path, Source::Directory(self.directories))
    }

    /// Capture a regular file at a logical path. Resolve source links during
    /// discovery; a mapped file itself is opened without following a final
    /// symlink. Declare the logical symlinks separately.
    ///
    /// # Errors
    /// Returns an error for a relative source or conflicting entry.
    pub fn add_file(
        &mut self,
        destination: TreePath,
        source: PathBuf,
        metadata: MappedMetadata,
    ) -> Result<()> {
        ensure!(source.is_absolute(), "mapped source must be absolute");
        self.insert(
            destination,
            Source::File {
                path: source,
                metadata,
            },
        )
    }

    /// Capture generated bytes (for example a preprocessed C source) without
    /// creating a separate temporary source file.
    ///
    /// # Errors
    /// Returns an error for a conflicting entry.
    pub fn add_bytes(
        &mut self,
        destination: TreePath,
        data: Vec<u8>,
        metadata: TreeMetadata,
    ) -> Result<()> {
        self.insert(destination, Source::Bytes { data, metadata })
    }

    /// Add a content-addressed input without opening its bytes.
    /// # Errors
    /// Returns an error for a conflicting logical entry.
    pub fn add_reference(
        &mut self,
        destination: TreePath,
        blob: BlobRef,
        metadata: TreeMetadata,
        provider: ReferenceBlobProvider,
    ) -> Result<()> {
        self.insert(
            destination,
            Source::Reference {
                blob,
                metadata,
                provider,
            },
        )
    }

    /// Add a sandbox-visible link. Its target is interpreted only within the
    /// materialized sandbox, never followed by the capture operation.
    ///
    /// # Errors
    /// Returns an error for a conflicting entry.
    pub fn add_symlink(
        &mut self,
        destination: TreePath,
        target: Vec<u8>,
        modified: TreeTimestamp,
    ) -> Result<()> {
        self.insert(destination, Source::Symlink { target, modified })
    }

    fn add_parents(&mut self) -> Result<()> {
        let mut parents = BTreeSet::new();
        for path in self.entries.keys() {
            for (index, _) in path
                .as_bytes()
                .iter()
                .enumerate()
                .filter(|(_, byte)| **byte == b'/')
            {
                parents.insert(TreePath::new(path.as_bytes()[..index].to_vec())?);
            }
        }
        for parent in parents {
            self.add_directory(parent)?;
        }
        Ok(())
    }

    /// Compute the input manifest without writing or staging any content.
    /// Retain source locators and verified metadata, not one open file per
    /// entry. Only missing content is opened again for transfer.
    ///
    /// The caller must keep the selected sources quiescent over the whole
    /// operation. Metadata checks detect changes but do not replace a snapshot.
    /// # Errors
    /// Returns an error for invalid topology, changed or unreadable sources.
    pub fn prepare(self) -> Result<PreparedTree> {
        self.prepare_inner(None, None)
    }

    /// Capture a trusted installed toolchain using a process-local digest
    /// memo. Fresh discovery still determines the entire tree topology.
    /// Only a matching regular-file stat version permits digest reuse.
    /// # Errors
    /// Returns an error for invalid topology, changed or unreadable sources.
    pub fn prepare_with_cache(self, cache: &SourceDigestCache) -> Result<PreparedTree> {
        self.prepare_inner(Some(cache), None)
    }

    /// Prepare mixed local and immutable reference inputs using the same tree
    /// identity and metadata normalization as ordinary mapped inputs.
    /// # Errors
    /// Returns an error for invalid content, topology, or a lost reference.
    pub fn prepare_with_references(self, resolver: &ReferenceResolver<'_>) -> Result<PreparedTree> {
        self.prepare_inner(None, Some(resolver))
    }

    fn prepare_inner(
        mut self,
        cache: Option<&SourceDigestCache>,
        resolver: Option<&ReferenceResolver<'_>>,
    ) -> Result<PreparedTree> {
        self.add_parents()?;
        let mut entries = BTreeMap::new();
        let mut sources = BTreeMap::new();
        let mut references = BTreeMap::new();
        for (path, source) in self.entries {
            let entry = match source {
                Source::Directory(metadata) => TreeEntry::Directory(metadata),
                Source::Symlink { target, modified } => TreeEntry::Symlink { target, modified },
                Source::Bytes { data, metadata } => {
                    let blob = BlobRef {
                        id: ContentId::of(&data),
                        size: u64::try_from(data.len())?,
                    };
                    // Generated immutable bytes supersede file locators: they
                    // are always available and cannot change after preparation.
                    match sources.entry(blob.id) {
                        std::collections::btree_map::Entry::Vacant(entry) => {
                            entry.insert(PreparedSource::Bytes(data.into()));
                        }
                        std::collections::btree_map::Entry::Occupied(mut entry) => {
                            if matches!(entry.get(), PreparedSource::File { .. }) {
                                entry.insert(PreparedSource::Bytes(data.into()));
                            }
                        }
                    }
                    TreeEntry::File { blob, metadata }
                }
                Source::Reference {
                    blob,
                    metadata,
                    provider,
                } => {
                    add_reference(&mut references, blob, provider)?;
                    TreeEntry::File { blob, metadata }
                }
                Source::File {
                    path,
                    metadata: policy,
                } => {
                    let (file, stat) = open_source(&path)?;
                    let reference = resolver.map_or(Ok(None), |resolve| resolve(&file, &path))?;
                    let blob = if let Some((blob, provider)) = &reference {
                        ensure!(
                            blob.size == u64::try_from(stat.st_size)?,
                            "referenced file length changed"
                        );
                        unchanged(&stat, &fstat(&file)?)?;
                        add_reference(&mut references, *blob, provider.clone())?;
                        *blob
                    } else {
                        match cache {
                            Some(cache) => cache.digest(&path, &file, &stat)?,
                            None => hash_open_source(&file, &stat)?,
                        }
                    };
                    let metadata = mapped_file_metadata(&stat, policy)?;
                    if reference.is_none() {
                        let file = PreparedFile { path, stat };
                        match sources.entry(blob.id) {
                            std::collections::btree_map::Entry::Vacant(entry) => {
                                entry.insert(PreparedSource::File {
                                    primary: file,
                                    alternatives: Vec::new(),
                                });
                            }
                            std::collections::btree_map::Entry::Occupied(mut entry) => {
                                if let PreparedSource::File {
                                    primary,
                                    alternatives,
                                } = entry.get_mut()
                                    && primary.path != file.path
                                {
                                    alternatives.push(file);
                                }
                            }
                        }
                    }
                    TreeEntry::File { blob, metadata }
                }
            };
            entries.insert(path, entry);
        }
        let manifest = TreeManifest {
            root: self.directories,
            entries,
        };
        let id = manifest.id()?;
        Ok(PreparedTree {
            id,
            manifest: Arc::new(manifest),
            sources: Arc::new(sources),
            references: Arc::new(references),
        })
    }
}

type References = BTreeMap<ContentId, (u64, Vec<ReferenceBlobProvider>)>;

fn add_reference(
    references: &mut References,
    blob: BlobRef,
    provider: ReferenceBlobProvider,
) -> Result<()> {
    let (size, providers) = references
        .entry(blob.id)
        .or_insert_with(|| (blob.size, Vec::new()));
    ensure!(*size == blob.size, "conflicting reference content lengths");
    if !providers.contains(&provider) {
        providers.push(provider);
    }
    Ok(())
}

fn mapped_file_metadata(stat: &Stat, policy: MappedMetadata) -> Result<TreeMetadata> {
    Ok(match policy {
        MappedMetadata::Preserve => metadata(stat)?,
        MappedMetadata::NormalizeTimestamp(modified) => TreeMetadata {
            mode: stat.st_mode & 0o7777,
            modified,
        },
        MappedMetadata::Normalize(modified) => TreeMetadata {
            mode: if stat.st_mode & 0o100 == 0 {
                0o644
            } else {
                0o755
            },
            modified,
        },
    })
}

fn open_source(path: &Path) -> Result<(File, Stat)> {
    let file = File::from(openat(
        CWD,
        path,
        OFlags::RDONLY | OFlags::CLOEXEC | OFlags::NOFOLLOW | OFlags::NONBLOCK,
        Mode::empty(),
    )?);
    let stat = fstat(&file)?;
    ensure!(
        FileType::from_raw_mode(stat.st_mode) == FileType::RegularFile,
        "capture source is not a regular file"
    );
    Ok((file, stat))
}

fn hash_open_source(file: &File, stat: &Stat) -> Result<BlobRef> {
    let size = u64::try_from(stat.st_size)?;
    let mut reader = file.take(size.checked_add(1).context("mapped file length overflow")?);
    let mut hash = blake3::Hasher::new();
    hash.update_reader(&mut reader)?;
    ensure!(reader.limit() == 1, "file size changed during capture");
    unchanged(stat, &fstat(file)?)?;
    Ok(BlobRef {
        id: ContentId(*hash.finalize().as_bytes()),
        size,
    })
}

#[derive(Clone)]
struct PreparedFile {
    path: PathBuf,
    stat: Stat,
}

impl PreparedFile {
    fn open(&self) -> Result<File> {
        let (file, current) = open_source(&self.path)?;
        unchanged(&self.stat, &current)?;
        Ok(file)
    }
}

#[derive(Clone)]
enum PreparedSource {
    File {
        primary: PreparedFile,
        alternatives: Vec<PreparedFile>,
    },
    Bytes(Arc<[u8]>),
}

/// A validated mapped manifest and direct readers for its unique content.
/// No local CAS, temporary archive, or persistent staging is needed.
#[derive(Clone)]
pub struct PreparedTree {
    id: TreeId,
    manifest: Arc<TreeManifest>,
    sources: Arc<BTreeMap<ContentId, PreparedSource>>,
    references: Arc<References>,
}

impl PreparedTree {
    /// Prepare an existing manifest using only an explicitly leased source.
    /// # Errors
    /// Returns an error for invalid topology or inconsistent content.
    pub fn from_references(
        manifest: TreeManifest,
        provider: &ReferenceBlobProvider,
    ) -> Result<Self> {
        let id = manifest.id()?;
        let references = manifest
            .blobs()?
            .into_iter()
            .map(|(id, size)| (id, (size, vec![provider.clone()])))
            .collect();
        Ok(Self {
            id,
            manifest: Arc::new(manifest),
            sources: Arc::new(BTreeMap::new()),
            references: Arc::new(references),
        })
    }

    #[must_use = "the identity names the manifest"]
    pub const fn id(&self) -> TreeId {
        self.id
    }

    #[must_use = "the manifest describes the selected build inputs"]
    pub fn manifest(&self) -> &TreeManifest {
        &self.manifest
    }

    /// Select only the requested paths and their directory ancestors without
    /// reopening any content. Selected hardlinks retain their inode topology;
    /// a hardlink whose original file is not selected becomes a regular file
    /// backed by the same blob. No unselected content is exposed by the result.
    ///
    /// # Errors
    /// Returns an error for an undeclared path or invalid projected topology.
    pub fn select_paths(&self, paths: impl IntoIterator<Item = TreePath>) -> Result<Self> {
        let mut selected = BTreeSet::new();
        for path in paths {
            let mut current = Some(path);
            while let Some(path) = current {
                ensure!(
                    self.manifest.entries.contains_key(&path),
                    "selected input path is not declared: {path:?}"
                );
                current = path.parent();
                if !selected.insert(path) {
                    break;
                }
            }
        }
        let mapping = selected.iter().map(|path| (path, path.clone())).collect();
        let mut manifest = TreeManifest {
            root: self.manifest.root,
            entries: BTreeMap::new(),
        };
        crate::recipe::project_entries(&self.manifest, &mapping, &mut manifest)?;
        // Projection does not normalize existing directory metadata. Unlike
        // a recipe union, this is a selection of one original tree.
        for path in &selected {
            if let Some(TreeEntry::Directory(metadata)) = self.manifest.entries.get(path) {
                manifest
                    .entries
                    .insert(path.clone(), TreeEntry::Directory(*metadata));
            }
        }
        let id = manifest.id()?;
        let blobs = manifest.blobs()?;
        let sources = self
            .sources
            .iter()
            .filter(|(id, _)| blobs.contains_key(id))
            .map(|(id, source)| (*id, source.clone()))
            .collect();
        let references = self
            .references
            .iter()
            .filter(|(id, _)| blobs.contains_key(id))
            .map(|(id, source)| (*id, source.clone()))
            .collect();
        Ok(Self {
            id,
            manifest: Arc::new(manifest),
            sources: Arc::new(sources),
            references: Arc::new(references),
        })
    }

    /// Reopen only an advertised source blob. The receiver must verify the
    /// exact content digest and length while consuming the returned reader.
    /// # Errors
    /// Returns an error for unknown content or a changed source file.
    pub fn open_blob(&self, id: ContentId) -> Result<Box<dyn Read + Send>> {
        let local = self.open_local_blob(id);
        if local.is_ok() {
            return local;
        }
        if let Some((size, providers)) = self.references.get(&id) {
            let mut last = None;
            for provider in providers {
                match provider.open(BlobRef { id, size: *size }) {
                    Ok(reader) => return Ok(reader),
                    Err(error) => last = Some(error),
                }
            }
            if let Some(error) = last {
                return Err(error.context("all leased content sources unavailable"));
            }
        }
        local
    }

    /// Inspect already-local bytes only. In particular, a result restore
    /// must not pull a lazy input merely to test whether it could reuse it.
    /// # Errors
    /// Returns an error for unknown, nonlocal or changed content.
    pub fn open_local_blob(&self, id: ContentId) -> Result<Box<dyn Read + Send>> {
        match self.sources.get(&id).context("undeclared mapped content")? {
            PreparedSource::File {
                primary,
                alternatives,
            } => match primary.open() {
                Ok(file) => Ok(Box::new(file)),
                Err(primary_error) => {
                    for source in alternatives {
                        if let Ok(file) = source.open() {
                            return Ok(Box::new(file));
                        }
                    }
                    Err(primary_error
                        .context("all prepared locators for this content are unavailable"))
                }
            },
            PreparedSource::Bytes(bytes) => Ok(Box::new(Cursor::new(Arc::clone(bytes)))),
        }
    }

    /// Import the prepared mapping into an explicitly selected local store.
    /// Existing blobs are negotiated and no redundant staging is performed.
    /// # Errors
    /// Returns an error for changed sources or storage failure.
    #[cfg(feature = "store")]
    pub fn import(&self, store: &crate::NativeStore) -> Result<crate::TreeLease> {
        let reserved = store.reserve_tree_upload(&self.manifest)?;
        let mut staged = Vec::new();
        for blob in reserved.missing() {
            staged.push(store.stage_expected(*blob, self.open_blob(blob.id)?)?);
        }
        store.publish_tree_pinned(&self.manifest, staged)
    }
}

