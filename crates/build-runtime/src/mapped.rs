    #[test]
    fn selected_tree_retains_only_selected_content_and_ancestors() -> Result<()> {
        let metadata = TreeMetadata {
            mode: 0o755,
            modified: TreeTimestamp {
                seconds: 123,
                nanoseconds: 0,
            },
        };
        let mut mapping = MappedTree::new(metadata);
        let selected = TreePath::new(b"lib/needed.a".to_vec())?;
        let other = TreePath::new(b"lib/other.a".to_vec())?;
        mapping.add_bytes(selected.clone(), b"needed".to_vec(), metadata)?;
        mapping.add_bytes(other, b"unrelated".to_vec(), metadata)?;
        let prepared = mapping.prepare()?;
        let projected = prepared.select_paths([selected.clone()])?;
        assert_ne!(projected.id(), prepared.id());
        assert_eq!(projected.manifest().entries.len(), 2);
        assert!(projected.manifest().entries.contains_key(&selected));
        assert!(projected.manifest().entries.contains_key(b"lib".as_slice()));
        assert!(projected.open_blob(ContentId::of(b"unrelated")).is_err());
        let mut bytes = Vec::new();
        projected
            .open_blob(ContentId::of(b"needed"))?
            .read_to_end(&mut bytes)?;
        assert_eq!(bytes, b"needed");
        assert!(
            prepared
                .select_paths([TreePath::new(b"missing".to_vec())?])
                .is_err()
        );
        Ok(())
    }

    #[test]
    fn selected_reference_tree_rehomes_hardlinks_without_opening_blobs() -> Result<()> {
        let metadata = TreeMetadata {
            mode: 0o755,
            modified: TreeTimestamp {
                seconds: 123,
                nanoseconds: 0,
            },
        };
        let blob = BlobRef {
            id: ContentId::of(b"leased"),
            size: 6,
        };
        let original = TreePath::new(b"original".to_vec())?;
        let alias = TreePath::new(b"alias".to_vec())?;
        let second = TreePath::new(b"second".to_vec())?;
        let manifest = TreeManifest {
            root: metadata,
            entries: BTreeMap::from([
                (original.clone(), TreeEntry::File { blob, metadata }),
                (alias.clone(), TreeEntry::Hardlink(original.clone())),
                (second.clone(), TreeEntry::Hardlink(original.clone())),
            ]),
        };
        let provider =
            ReferenceBlobProvider::new(|_| anyhow::bail!("projection must not open blobs"));
        let prepared = PreparedTree::from_references(manifest, &provider)?;
        let projected = prepared.select_paths([alias.clone(), second.clone()])?;
        assert_eq!(
            projected.manifest().entries[&alias],
            TreeEntry::File { blob, metadata }
        );
        assert_eq!(
            projected.manifest().entries[&second],
            TreeEntry::Hardlink(alias)
        );
        assert!(!projected.manifest().entries.contains_key(&original));
        Ok(())
    }

    #[test]
    fn mapped_paths_normalize_metadata_and_deduplicate_content() -> Result<()> {
        let dir = tempfile::tempdir()?;
        let source = dir.path().join("source");
        fs::write(&source, b"selected")?;
        fs::set_permissions(&source, fs::Permissions::from_mode(0o711))?;
        let store = NativeStore::open(&dir.path().join("store"))?;
        let modified = TreeTimestamp {
            seconds: 123,
            nanoseconds: 0,
        };
        let directories = TreeMetadata {
            mode: 0o755,
            modified,
        };
        let mut mapping = MappedTree::new(directories);
        mapping.add_file(
            TreePath::new(b"compiler/bin/tool".to_vec())?,
            source,
            MappedMetadata::Normalize(modified),
        )?;
        mapping.add_bytes(
            TreePath::new(b"generated/input".to_vec())?,
            b"selected".to_vec(),
            TreeMetadata {
                mode: 0o644,
                modified,
            },
        )?;
        mapping.add_symlink(
            TreePath::new(b"bin/tool".to_vec())?,
            b"/compiler/bin/tool".to_vec(),
            modified,
        )?;
        let tree = mapping.prepare()?.import(&store)?;
        assert_eq!(tree.manifest().blobs()?.len(), 1);
        let TreeEntry::File { blob, metadata } =
            tree.manifest().entries[&TreePath::new(b"compiler/bin/tool".to_vec())?]
        else {
            anyhow::bail!("expected mapped executable");
        };
        assert_eq!(metadata.mode, 0o755);
        let mut bytes = Vec::new();
        tree.open_blob(blob.id)?.read_to_end(&mut bytes)?;
        assert_eq!(bytes, b"selected");
        Ok(())
    }

    #[test]
    fn identical_artifact_bytes_with_different_mtime_change_preserved_tree_identity() -> Result<()>
    {
        let dir = tempfile::tempdir()?;
        let path = dir.path().join("artifact");
        fs::write(&path, b"identical dependency bytes")?;
        let stable = TreeTimestamp {
            seconds: 1,
            nanoseconds: 0,
        };
        let root = TreeMetadata {
            mode: 0o755,
            modified: stable,
        };
        let prepare = |seconds, policy| -> Result<PreparedTree> {
            File::open(&path)?.set_times(fs::FileTimes::new().set_modified(
                std::time::SystemTime::UNIX_EPOCH + std::time::Duration::from_secs(seconds),
            ))?;
            let mut tree = MappedTree::new(root);
            tree.add_file(TreePath::new(b"artifact".to_vec())?, path.clone(), policy)?;
            tree.prepare()
        };
        let first = prepare(100, MappedMetadata::Preserve)?;
        let second = prepare(200, MappedMetadata::Preserve)?;
        assert_eq!(first.manifest().blobs()?, second.manifest().blobs()?);
        assert_ne!(first.id(), second.id());
        let first = prepare(100, MappedMetadata::NormalizeTimestamp(stable))?;
        let second = prepare(200, MappedMetadata::NormalizeTimestamp(stable))?;
        assert_eq!(first.id(), second.id());
        Ok(())
    }

