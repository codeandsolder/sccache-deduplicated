//! Capture a selected filesystem layout directly into the content store.
//! A mapping is not an archive and never materializes an intermediate tree.

use std::{
    collections::{BTreeMap, BTreeSet, btree_map::Entry},
    fs::File,
    path::PathBuf,
};

use anyhow::{Result, ensure};
use rustix::fs::{CWD, Mode, OFlags, fstat, openat};

use super::capture::{capture_regular, metadata};
use crate::{
    ContentId, NativeStore, StagedBlob, TreeEntry, TreeLease, TreeManifest, TreeMetadata, TreePath,
    TreeTimestamp,
};

/// File metadata contract for a mapped build tree. Normalization is explicit
/// and affects the actual materialized inode, not merely its cache key.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MappedMetadata {
    Preserve,
    Normalize(TreeTimestamp),
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum Source {
    Directory(TreeMetadata),
    File {
        path: PathBuf,
        metadata: MappedMetadata,
    },
    Bytes {
        data: Vec<u8>,
        metadata: TreeMetadata,
    },
    Symlink {
        target: Vec<u8>,
        modified: TreeTimestamp,
    },
}

/// A collection of caller-selected files, generated bytes and symlinks at
/// canonical sandbox-relative paths. Implicit parent directories get the
/// explicit directory metadata supplied at construction.
pub struct MappedTree {
    directories: TreeMetadata,
    entries: BTreeMap<TreePath, Source>,
}

impl MappedTree {
    #[must_use = "the mapping must be populated and captured"]
    pub const fn new(directories: TreeMetadata) -> Self {
        Self {
            directories,
            entries: BTreeMap::new(),
        }
    }

    fn insert(&mut self, path: TreePath, source: Source) -> Result<()> {
        match self.entries.entry(path) {
            Entry::Vacant(entry) => {
                entry.insert(source);
            }
            Entry::Occupied(entry) => {
                ensure!(entry.get() == &source, "conflicting mapped tree paths");
            }
        }
        Ok(())
    }

    /// Add a directory with the mapping's directory metadata.
    ///
    /// # Errors
    /// Returns an error for a conflicting entry.
    pub fn add_directory(&mut self, path: TreePath) -> Result<()> {
        self.insert(path, Source::Directory(self.directories))
    }

    /// Capture a regular file at a logical path. Resolve source links during
    /// discovery; a mapped file itself is opened without following a final
    /// symlink. Declare the logical symlinks separately.
    ///
    /// # Errors
    /// Returns an error for a relative source or conflicting entry.
    pub fn add_file(
        &mut self,
        destination: TreePath,
        source: PathBuf,
        metadata: MappedMetadata,
    ) -> Result<()> {
        ensure!(source.is_absolute(), "mapped source must be absolute");
        self.insert(
            destination,
            Source::File {
                path: source,
                metadata,
            },
        )
    }

    /// Capture generated bytes (for example a preprocessed C source) without
    /// creating a separate temporary source file.
    ///
    /// # Errors
    /// Returns an error for a conflicting entry.
    pub fn add_bytes(
        &mut self,
        destination: TreePath,
        data: Vec<u8>,
        metadata: TreeMetadata,
    ) -> Result<()> {
        self.insert(destination, Source::Bytes { data, metadata })
    }

    /// Add a sandbox-visible link. Its target is interpreted only within the
    /// materialized sandbox, never followed by the capture operation.
    ///
    /// # Errors
    /// Returns an error for a conflicting entry.
    pub fn add_symlink(
        &mut self,
        destination: TreePath,
        target: Vec<u8>,
        modified: TreeTimestamp,
    ) -> Result<()> {
        self.insert(destination, Source::Symlink { target, modified })
    }

    fn add_parents(&mut self) -> Result<()> {
        let mut parents = BTreeSet::new();
        for path in self.entries.keys() {
            for (index, _) in path
                .as_bytes()
                .iter()
                .enumerate()
                .filter(|(_, byte)| **byte == b'/')
            {
                parents.insert(TreePath::new(path.as_bytes()[..index].to_vec())?);
            }
        }
        for parent in parents {
            self.add_directory(parent)?;
        }
        Ok(())
    }

    /// Read selected files directly into verified CAS staging and publish
    /// one tree. The caller must keep the selected sources quiescent over
    /// the whole capture. Per-file before/after metadata detects mutation.
    ///
    /// # Errors
    /// Returns an error for invalid topology, changed source files, or
    /// storage failure.
    pub fn capture(mut self, store: &NativeStore) -> Result<TreeLease> {
        self.add_parents()?;
        let mut entries = BTreeMap::new();
        let mut staged = BTreeMap::new();
        for (path, source) in self.entries {
            let entry = match source {
                Source::Directory(metadata) => TreeEntry::Directory(metadata),
                Source::Symlink { target, modified } => TreeEntry::Symlink { target, modified },
                Source::Bytes { data, metadata } => {
                    let size = u64::try_from(data.len())?;
                    let blob = store.stage_inner(data.as_slice(), Some(size))?;
                    staged_file(blob, metadata, &mut staged)
                }
                Source::File {
                    path,
                    metadata: policy,
                } => {
                    let file = File::from(openat(
                        CWD,
                        &path,
                        OFlags::RDONLY | OFlags::CLOEXEC | OFlags::NOFOLLOW | OFlags::NONBLOCK,
                        Mode::empty(),
                    )?);
                    let stat = fstat(&file)?;
                    let blob = capture_regular(store, &file, &stat)?;
                    let metadata = match policy {
                        MappedMetadata::Preserve => metadata(&stat)?,
                        MappedMetadata::Normalize(modified) => TreeMetadata {
                            mode: if stat.st_mode & 0o100 == 0 {
                                0o644
                            } else {
                                0o755
                            },
                            modified,
                        },
                    };
                    staged_file(blob, metadata, &mut staged)
                }
            };
            entries.insert(path, entry);
        }
        // Mapped paths are deliberately independent files (not hardlinks);
        // the mapping does not infer alias topology from host inode numbers.
        // The physical content is still deduplicated by the shared CAS.
        store.publish_tree_pinned(
            &TreeManifest {
                root: self.directories,
                entries,
            },
            staged.into_values().collect(),
        )
    }
}

fn staged_file(
    blob: StagedBlob,
    metadata: TreeMetadata,
    staged: &mut BTreeMap<ContentId, StagedBlob>,
) -> TreeEntry {
    let reference = blob.reference();
    staged.entry(reference.id).or_insert(blob);
    TreeEntry::File {
        blob: reference,
        metadata,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::{
        fs,
        io::Read,
        os::unix::fs::{PermissionsExt, symlink},
    };

    #[test]
    fn mapped_paths_normalize_metadata_and_deduplicate_content() -> Result<()> {
        let dir = tempfile::tempdir()?;
        let source = dir.path().join("source");
        fs::write(&source, b"selected")?;
        fs::set_permissions(&source, fs::Permissions::from_mode(0o711))?;
        let store = NativeStore::open(&dir.path().join("store"))?;
        let modified = TreeTimestamp {
            seconds: 123,
            nanoseconds: 0,
        };
        let directories = TreeMetadata {
            mode: 0o755,
            modified,
        };
        let mut mapping = MappedTree::new(directories);
        mapping.add_file(
            TreePath::new(b"compiler/bin/tool".to_vec())?,
            source,
            MappedMetadata::Normalize(modified),
        )?;
        mapping.add_bytes(
            TreePath::new(b"generated/input".to_vec())?,
            b"selected".to_vec(),
            TreeMetadata {
                mode: 0o644,
                modified,
            },
        )?;
        mapping.add_symlink(
            TreePath::new(b"bin/tool".to_vec())?,
            b"/compiler/bin/tool".to_vec(),
            modified,
        )?;
        let tree = mapping.capture(&store)?;
        assert_eq!(tree.manifest().blobs()?.len(), 1);
        let TreeEntry::File { blob, metadata } =
            tree.manifest().entries[&TreePath::new(b"compiler/bin/tool".to_vec())?]
        else {
            anyhow::bail!("expected mapped executable");
        };
        assert_eq!(metadata.mode, 0o755);
        let mut bytes = Vec::new();
        tree.open_blob(blob.id)?.read_to_end(&mut bytes)?;
        assert_eq!(bytes, b"selected");
        Ok(())
    }

    #[test]
    fn mapping_rejects_nondirectory_ancestors_and_source_symlinks() -> Result<()> {
        let dir = tempfile::tempdir()?;
        let store = NativeStore::open(&dir.path().join("store"))?;
        let modified = TreeTimestamp {
            seconds: 1,
            nanoseconds: 0,
        };
        let directories = TreeMetadata {
            mode: 0o755,
            modified,
        };
        let mut mapping = MappedTree::new(directories);
        mapping.add_symlink(
            TreePath::new(b"alias".to_vec())?,
            b"/elsewhere".to_vec(),
            modified,
        )?;
        mapping.add_directory(TreePath::new(b"alias/child".to_vec())?)?;
        assert!(mapping.capture(&store).is_err());
        let actual = dir.path().join("actual");
        fs::write(&actual, b"content")?;
        let link = dir.path().join("link");
        symlink(&actual, &link)?;
        let mut mapping = MappedTree::new(directories);
        mapping.add_file(
            TreePath::new(b"file".to_vec())?,
            link,
            MappedMetadata::Preserve,
        )?;
        assert!(mapping.capture(&store).is_err());
        Ok(())
    }
}
